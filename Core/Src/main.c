/* Debug log helper: printf-style output over USART1 (RF port). */
static void dbg_log(const char *fmt, ...)
{
  char buf[128];
  va_list args;
  int len;

  va_start(args, fmt);
  len = vsnprintf(buf, sizeof(buf), fmt, args);
  va_end(args);

  if (len > 0)
  {
    uint16_t tx_len = (uint16_t)((len < (int)sizeof(buf)) ? len : (int)(sizeof(buf) - 1));
    HAL_UART_Transmit(&huart1, (uint8_t *)buf, tx_len, 1000);
  }
}

